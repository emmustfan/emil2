export const PAYMENT_NOTE =
  "Сумма и период указаны в каждом тарифе. Автопродление подтверждается отдельно; следующие списания можно отключить в кабинете.";
export function upgradeBillingCopy<
  T extends {
    paymentNote: string;
    faq: { question: string; answer: string }[];
  },
>(content: T): T {
  return {
    ...content,
    paymentNote:
      content.paymentNote === OLD_PAYMENT_NOTE
        ? PAYMENT_NOTE
        : content.paymentNote,
    faq: content.faq.map((f) => ({
      ...f,
      answer:
        PAYMENT_FAQ_UPDATES.find(([old]) => old === f.answer)?.[1] ?? f.answer,
    })),
  };
}
